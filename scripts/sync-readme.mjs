import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { collections } from '../book.mjs'
import { englishCollections, englishTitles, englishArticlePath } from '../book.en.mjs'
import { tagDefinitions } from '../article-tags.mjs'
import { articleHistory } from '../article-history.mjs'
import { recentArticles } from '../recent-articles.mjs'
import { recentVersions, recentModuleArticles } from '../open-etf-topic.mjs'
import { renderRecentModuleLinks } from './sync-readme-modules.mjs'
import legacyAnchors from '../data/readme/legacy-anchors.json' with { type: 'json' }

const root = fileURLToPath(new URL('../', import.meta.url))
const items = collections.flatMap(c => c.chapters.flatMap(ch => ch.items))
const site = language => `https://hpoenixf.com/eff-agent-article/${language === 'en' ? 'en/' : ''}`
const markdownLink = (title, path) => `[${title.replaceAll('|', '\\|')}](${path})`
export function readmeRecent(history, limit = 3) {
  // One source edition per identity; use the site's visibility and stable sorting owner.
  const pages = items.map(([slug]) => {
    const content = readFileSync(new URL(`../articles/${slug}.md`, import.meta.url), 'utf8')
    const header = /^---\n([\s\S]*?)\n---/.exec(content)?.[1] || ''
    const frontmatter = {}
    for (const key of ['draft', 'published']) {
      const value = new RegExp(`^${key}:\\s*(true|false)\\s*$`, 'm').exec(header)?.[1]
      if (value) frontmatter[key] = value
    }
    return { url: '/articles/' + slug, frontmatter }
  })
  return recentArticles(pages, { items, history, language: 'zh', limit })
}
export function renderVersions(language, versions = recentVersions) {
  return versions.slice(0, 3).map(v => `- ${markdownLink('v' + v.version + ' · ' + (language === 'zh' ? v.zh : v.title), v.href)}${v.phase ? ` · ${v.phase}` : ''}`).join('\n')
}
export function renderReadme(language, history) {
  const en = language === 'en'
  const template = readFileSync(new URL(`../data/readme/README.${language}.md`, import.meta.url), 'utf8')
  const categoryLines = (en ? englishCollections : collections).map(c => `- **${markdownLink(c.title, site(language) + c.id)}** — ${c.subtitle}`)
  const topicLines = tagDefinitions.map(t => `- ${markdownLink(t[language], site(language) + 'catalog?tags=' + t.id)} · ${markdownLink(en ? 'Reading guide' : '专题导读', site(language) + t.path)}`)
  const recent = readmeRecent(history).map(row => {
    const translated = englishArticlePath(row.slug).startsWith('/en/')
    const title = en && translated ? englishTitles[row.slug] : row.title
    const path = (en && translated ? 'en/' : '') + 'articles/' + row.slug + '.md'
    const label = row.kind === 'new' ? (en ? 'New' : '新增') : (en ? 'Updated' : '更新')
    return `- ${row.date} · ${label} · ${markdownLink(title, path)}${en && !translated ? ' (Chinese original)' : ''}`
  }).join('\n') || (en ? 'No qualified article history is available.' : '暂无可核实的文章历史。')
  const modules = en ? recentModuleArticles('en').map(row => '- ' + markdownLink(row.title, row.href.replace(/^\//, '') + '.md')).join('\n') : renderRecentModuleLinks()
  // Legacy GitHub heading fragments remain addressable, without keeping stale claims on the front page.
  const slug = value => value.toLowerCase().replace(/[^\p{L}\p{N}_\- ]/gu, '').replaceAll(' ', '-')
  const current = new Set([...template.matchAll(/^#{1,6} (.+)$/gm)].map(m => slug(m[1])))
  const legacy = '<details>\n<summary>旧 README 深链与原始记录</summary>\n\n' + legacyAnchors.filter(id => !current.has(id)).map(id => `<a id="${id}"></a>`).join('\n') + '\n\n[查看原 README 完整快照](https://github.com/hpoenixf/eff-agent-article/blob/75916debf634279af4a6521569a38eb93dfff142/README.md)。旧日期与版本主张保留在固定历史中，不再作为当前首页信息。\n\n</details>'
  const blocks = { COLLECTIONS: categoryLines.join('\n'), TOPICS: topicLines.join('\n'), RECENT: recent, VERSIONS: renderVersions(language), MODULES: modules, LEGACY: legacy }
  return '<!-- Generated by scripts/sync-readme.mjs; edit data/readme and canonical sources. -->\n' + template.replace(/\{\{([A-Z]+)\}\}/g, (_, key) => { if (!(key in blocks)) throw new Error('Unknown README block ' + key); return blocks[key] })
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const mode = process.argv[2]
  if (!['--write', '--check'].includes(mode) || process.argv.length !== 3) throw new Error('Usage: node scripts/sync-readme.mjs --write|--check')
  const history = articleHistory(root, items.map(([slug]) => `articles/${slug}.md`))
  for (const language of ['zh', 'en']) {
    const path = new URL(language === 'zh' ? '../README.md' : '../README.en.md', import.meta.url)
    const output = renderReadme(language, history)
    if (mode === '--write') writeFileSync(path, output)
    else if (readFileSync(path, 'utf8') !== output) throw new Error('README differs from canonical sources; run npm run readme:sync')
  }
  console.log('Bilingual READMEs match canonical categories, topics, article history, and versions')
}
